export const DICT = { en, it };
export type Key = keyof typeof en;

export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  return DICT[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

const LOCALE: Record<Lang, string> = { en: 'en-IE', it: 'it-IT' };
export const money = (lang: Lang, cents: number) =>
  new Intl.NumberFormat(LOCALE[lang], { style: 'currency', currency: 'EUR', minimumFractionDigits: cents % 100 ? 2 : 0 }).format(cents / 100);
export const dateTime = (lang: Lang, ms: number) =>
  new Intl.DateTimeFormat(LOCALE[lang], { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit', timeZone: 'Europe/Rome' }).format(ms);

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('sm-lang');
    if (saved === 'en' || saved === 'it') return saved;
  } catch { /* storage off */ }
  return navigator.language?.toLowerCase().startsWith('it') ? 'it' : 'en';
}
